"""Shared plumbing for run folders that export cases, analyze them and merge the results.

Used by ``custom_fetch`` (run-specific query):
run-folder naming, harness config generation, the ``copilot-batch-run`` commands and
the final merge into ``cases_with_summaries.xlsx``.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import Any, Iterable, Sequence

import yaml

from .report_merge import MergeResult, merge_analysis_run
from .salesforce_export.export import CASES_WORKBOOK_FILENAME, COUNT_SUFFIX, MAIN_SHEET

MERGED_WORKBOOK_FILENAME = "cases_with_summaries.xlsx"

# Columns sent to the model by default, in order; columns missing from the export are skipped.
DEFAULT_MODEL_FIELDS: tuple[str, ...] = (
    "Subject",
    "Status",
    "CreatedDate",
    "ClosedDate",
    "Account.Name",
    "HRCSVC_Asset_s_Model_Description__c",
    "Asset.Name",
    "HRCSVC_Software_Version__r.Name",
    "HRCSVC_Main_Sub_Assembly__r.Name",
    "HRCSVC_Complaint_Code__r.Name",
    "HRCSVC_Case_Resolution__c",
    "Case_Resolution_ReadOnly__c",
    "Problem Codes",
    "Complaint Qualifications",
)

# Fallback when none of DEFAULT_MODEL_FIELDS were exported: skip identifiers and noise.
_NOISE_MARKERS = ("serial", "udi", "jde_", "billing", "rma_number", "owner.")


class AnalysisRunError(Exception):
    """Raised when an analysis run cannot be prepared or finalized."""


def new_run_dir(runs_root: Path, base_name: str, day: date) -> Path:
    """Return an unused ``<base_name>_<date>`` folder, adding ``_2``, ``_3``... if taken."""
    base = f"{base_name}_{day.isoformat()}"
    candidate = runs_root / base
    suffix = 2
    while candidate.exists():
        candidate = runs_root / f"{base}_{suffix}"
        suffix += 1
    return candidate


def select_model_fields(
    columns: Sequence[str],
    preferred: Iterable[str] = DEFAULT_MODEL_FIELDS,
) -> list[str]:
    """Pick the exported columns to send to the model (case-insensitive, preferred order)."""
    present = {column.lower(): column for column in columns}
    fields = [present[name.lower()] for name in preferred if name.lower() in present]
    if fields:
        return fields
    return [
        column
        for column in columns
        if column.lower() != "id"
        and not column.endswith(COUNT_SUFFIX)
        and not any(marker in column.lower() for marker in _NOISE_MARKERS)
    ]


def build_config(
    run_dir: Path,
    *,
    analysis: str,
    version: str,
    id_field: str,
    fields: Sequence[str],
    concurrency: int = 3,
    max_output_tokens: int = 900,
    dataset_path: Path | None = None,
) -> dict[str, Any]:
    """Harness config for a run folder; all paths absolute so the CWD does not matter."""
    if not fields:
        raise AnalysisRunError("no exported columns are available to send to the model")
    return {
        "dataset": {
            "path": str((dataset_path or run_dir / CASES_WORKBOOK_FILENAME).resolve()),
            "sheet": MAIN_SHEET,
            "id_field": id_field,
            "fields": list(fields),
            "filters": [],
            "limit": None,
        },
        "analysis": {
            "name": analysis,
            "version": version,
            "concurrency": concurrency,
            "max_output_tokens": max_output_tokens,
            "temperature": 0,
        },
        "rate_limits": {"rpm": None, "tpm": None, "max_attempts": 4},
        "cache": {"mode": "off"},
        "output": {"runs_dir": str(run_dir.resolve())},
    }


def write_config(path: Path, config: dict[str, Any]) -> None:
    header = (
        "# Generated by complaint_analyzer; edit only if you know why.\n"
        "# cache.mode is quoted so YAML does not read it as boolean false.\n"
    )
    text = yaml.safe_dump(config, sort_keys=False, allow_unicode=True)
    text = text.replace("mode: 'off'", 'mode: "off"').replace("mode: off", 'mode: "off"')
    path.write_text(header + text, encoding="utf-8")


def harness_commands(config_path: Path, run_id: str, batch_size: int = 10) -> dict[str, str]:
    """The copilot-batch-run commands for a run (``--limit 0`` = every case)."""
    common = f'--config "{config_path}" --backend harness --limit 0 --run-id {run_id}'
    python = r".\.venv\Scripts\python.exe -m complaint_analyzer"
    return {
        "prepare": f"{python} {common} --prepare --batch-size {batch_size}",
        "check": f"{python} {common} --check --no-echo",
        "finalize": f"{python} {common} --finalize",
    }


def merge_run(
    run_dir: Path,
    *,
    analysis: str,
    run_id: str,
    id_field: str,
    row_count: int,
    notes: list[str],
    allow_incomplete: bool = False,
) -> tuple[MergeResult, dict[str, Any]]:
    """Merge the harness results into ``cases_with_summaries.xlsx``.

    Returns the merge result and the ``merge`` block to store in ``session.json``.
    """
    harness_dir = run_dir / run_id
    manifest = harness_dir / "manifest.json"
    if row_count and not allow_incomplete and not manifest.is_file():
        raise AnalysisRunError(
            f"harness run '{run_id}' is not finalized (no manifest.json in {harness_dir}); "
            "finish copilot-batch-run first or pass --allow-incomplete"
        )
    result = merge_analysis_run(
        run_dir / CASES_WORKBOOK_FILENAME,
        harness_dir,
        run_dir / MERGED_WORKBOOK_FILENAME,
        analysis=analysis,
        id_field=id_field,
        notes=notes,
        allow_missing_results=allow_incomplete,
    )
    info = {
        "workbook": MERGED_WORKBOOK_FILENAME,
        "rows": result.row_count,
        "matched": result.matched,
        "status_counts": dict(result.status_counts),
        "unmatched_results": result.unmatched_results,
        "generated_columns": list(result.generated_columns),
        "run_manifest": str(manifest.relative_to(run_dir)) if manifest.is_file() else None,
    }
    return result, info
