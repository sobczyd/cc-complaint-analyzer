WORKFLOWS: dict[str, Workflow] = {NURSE_CALL_7D.name: NURSE_CALL_7D}


def get_workflow(name: str) -> Workflow:
    try:
        return WORKFLOWS[name]
    except KeyError:
        raise SessionError(
            f"unknown workflow '{name}'; available: {', '.join(sorted(WORKFLOWS))}"
        ) from None


def session_folder_name(workflow: Workflow, day: date) -> str:
    return f"{workflow.query_set}_{day.isoformat()}"


def new_session_dir(runs_root: Path, workflow: Workflow, day: date) -> Path:
    """Return an unused ``<query_set>_<date>`` folder, adding ``_2``, ``_3``... if taken."""
    base = session_folder_name(workflow, day)
    candidate = runs_root / base
    suffix = 2
    while candidate.exists():
        candidate = runs_root / f"{base}_{suffix}"
        suffix += 1
    return candidate


def build_config(workflow: Workflow, session_dir: Path, columns: list[str]) -> dict[str, Any]:
    """Harness config for the session; all paths absolute so the CWD does not matter."""
    present = {column.lower(): column for column in columns}
    fields = [present[name.lower()] for name in workflow.model_fields if name.lower() in present]
    if not fields:
        raise SessionError(
            f"none of the model fields for '{workflow.name}' are in the exported columns"
        )
    return {
        "dataset": {
            "path": str((session_dir / CASES_WORKBOOK_FILENAME).resolve()),
            "sheet": MAIN_SHEET,
            "id_field": workflow.id_field,
            "fields": fields,
            "filters": [],
            "limit": None,
        },
        "analysis": {
            "name": workflow.analysis,
            "version": workflow.analysis_version,
            "concurrency": workflow.concurrency,
            "max_output_tokens": workflow.max_output_tokens,
            "temperature": 0,
        },
        "rate_limits": {"rpm": None, "tpm": None, "max_attempts": 4},
        "cache": {"mode": "off"},
        "output": {"runs_dir": str(session_dir.resolve())},
    }


def write_config(path: Path, config: dict[str, Any]) -> None:
    header = (
        "# Generated by complaint_analyzer.daily; edit only if you know why.\n"
        "# cache.mode is quoted so YAML does not read it as boolean false.\n"
    )
    text = yaml.safe_dump(config, sort_keys=False, allow_unicode=True)
    text = text.replace("mode: 'off'", 'mode: "off"').replace("mode: off", 'mode: "off"')
    path.write_text(header + text, encoding="utf-8")


def harness_commands(config_path: Path, run_id: str, batch_size: int = 10) -> dict[str, str]:
    """The copilot-batch-run commands for this session (``--limit 0`` = every case)."""
    common = f'--config "{config_path}" --backend harness --limit 0 --run-id {run_id}'
    python = r".\.venv\Scripts\python.exe -m complaint_analyzer"
    return {
        "prepare": f"{python} {common} --prepare --batch-size {batch_size}",
        "check": f"{python} {common} --check --no-echo",
        "finalize": f"{python} {common} --finalize",
    }


def read_session(session_dir: Path) -> dict[str, Any]:
    path = session_dir / SESSION_FILENAME
    if not path.is_file():
        raise SessionError(f"not a daily session folder (no {SESSION_FILENAME}): {session_dir}")
    return json.loads(path.read_text(encoding="utf-8"))


def write_session(session_dir: Path, data: dict[str, Any]) -> None:
    (session_dir / SESSION_FILENAME).write_text(
        json.dumps(data, indent=2) + "\n", encoding="utf-8"
    )


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


@dataclass
class InitResult:
    session_dir: Path
    export: ExportResult
    config_path: Path | None
    run_id: str
    commands: dict[str, str] = field(default_factory=dict)

    @property
    def needs_batch_run(self) -> bool:
        return self.export.row_count > 0


def init_session(
    workflow: Workflow,
    *,
    runs_root: Path = DEFAULT_RUNS_ROOT,
    day: date | None = None,
    target_org: str | None = None,
    from_json: Path | None = None,
    query_version: str | None = None,
    batch_size: int = 10,
) -> InitResult:
    """Create the session folder, export the cases and write the harness config."""
    day = day or date.today()
    session_dir = new_session_dir(runs_root, workflow, day)
    session_dir.mkdir(parents=True)

    export = export_query_set(
        workflow.query_set,
        session_dir,
        version=query_version,
        target_org=target_org,
        from_json=from_json,
        id_field=workflow.id_field,
    )

    config_path: Path | None = None
    commands: dict[str, str] = {}
    if export.row_count:
        config_path = session_dir / workflow.config_filename
        write_config(config_path, build_config(workflow, session_dir, list(export.columns)))
        commands = harness_commands(config_path.resolve(), workflow.run_id, batch_size)

    write_session(
        session_dir,
        {
            "workflow": workflow.name,
            "description": workflow.description,
            "session_dir": str(session_dir.resolve()),
            "created_at": _now(),
            "export": export.as_json(),
            "analysis": {
                "name": workflow.analysis,
                "version": workflow.analysis_version,
                "run_id": workflow.run_id,
                "config": config_path.name if config_path else None,
                "skipped": not export.row_count,
            },
            "harness_commands": commands,
            "finalized_at": None,
            "merge": None,
        },
    )
    return InitResult(
        session_dir=session_dir,
        export=export,
        config_path=config_path,
        run_id=workflow.run_id,
        commands=commands,
    )


def finalize_session(session_dir: Path, *, allow_incomplete: bool = False) -> MergeResult:
    """Merge the harness results into ``cases_with_summaries.xlsx`` and update session.json."""
    session = read_session(session_dir)
    workflow = get_workflow(session["workflow"])
    analysis = session["analysis"]
    run_dir = session_dir / analysis["run_id"]
    row_count = int(session["export"]["row_count"])

    if row_count and not allow_incomplete and not (run_dir / "manifest.json").is_file():
        raise SessionError(
            f"harness run '{analysis['run_id']}' is not finalized (no manifest.json in {run_dir}); "
            "finish copilot-batch-run first or pass --allow-incomplete"
        )

    export = session["export"]
    notes = [
        f"Workflow: {workflow.name}",
        f"Query set: {export['query_set']} {export['version']}"
        + (f" (org {export['target_org']})" if export.get("target_org") else ""),
        f"Exported at: {export.get('exported_at', '')}",
        f"Prompt: {analysis['name']} {analysis['version']} (run id {analysis['run_id']})",
    ]
    if not row_count:
        notes.append("No cases were returned; the batch run was skipped.")

    result = merge_analysis_run(
        session_dir / CASES_WORKBOOK_FILENAME,
        run_dir,
        session_dir / MERGED_WORKBOOK_FILENAME,
        analysis=analysis["name"],
        id_field=workflow.id_field,
        notes=notes,
        allow_missing_results=allow_incomplete,
    )

    run_manifest = run_dir / "manifest.json"
    session["finalized_at"] = _now()
    session["merge"] = {
        "workbook": MERGED_WORKBOOK_FILENAME,
        "rows": result.row_count,
        "matched": result.matched,
        "status_counts": dict(result.status_counts),
        "unmatched_results": result.unmatched_results,
        "generated_columns": list(result.generated_columns),
        "run_manifest": str(run_manifest.relative_to(session_dir)) if run_manifest.is_file() else None,
    }
    write_session(session_dir, session)
    return result


